/**
 * Otevře/zavře dropdown pro výběr jazyka a bezpečně ho napozicuje pod tlačítko
 */
function toggleLangDropdown(event) {
    if (event) {
        if (typeof event.stopPropagation === "function") event.stopPropagation();
        if (typeof event.preventDefault === "function") event.preventDefault();
    }
    const dropdown = document.getElementById("langDropdown");
    const btn = document.getElementById("btnLangSwitcher");
    if (!dropdown) {
        console.warn("Element #langDropdown nebyl v DOM nalezen");
        return;
    }

    const willOpen = dropdown.classList.contains("hidden");
    if (willOpen) {
        if (btn) {
            const rect = btn.getBoundingClientRect();
            dropdown.style.position = "fixed";
            dropdown.style.top = Math.round(rect.bottom + 6) + "px";
            dropdown.style.right = Math.max(8, Math.round(window.innerWidth - rect.right)) + "px";
            dropdown.style.left = "auto";
            dropdown.style.zIndex = "99999";
        }
        dropdown.classList.remove("hidden");
    } else {
        dropdown.classList.add("hidden");
    }
}
window.toggleLangDropdown = toggleLangDropdown;

/**
 * Změní aktivní jazyk aplikace (CS, EN, FR) a přeloží celé rozhraní
 */
function setAppLanguage(lang) {
    if (!["cs", "en", "fr"].includes(lang)) lang = "cs";
    window.currentLanguage = lang;
    if (typeof currentLanguage !== "undefined") {
        currentLanguage = lang;
    }
    try {
        localStorage.setItem("medstudio_lang", lang);
    } catch(e) {}

    updateLangUI();

    try {
        window.dispatchEvent(new CustomEvent("medstudio_lang_change", { detail: { lang } }));
    } catch(e) {}

    const dropdown = document.getElementById("langDropdown");
    if (dropdown) dropdown.classList.add("hidden");

    const langNames = {
        cs: "Čeština (AI bude generovat a odpovídat česky)",
        en: "English (AI will generate and respond in English)",
        fr: "Français (L'IA va générer et répondre en français)"
    };
    if (typeof showGlobalToast === "function") {
        showGlobalToast(`🌐 ${langNames[lang] || lang.toUpperCase()}`, "success");
    }
}
window.setAppLanguage = setAppLanguage;

/**
 * Aktualizuje vlajku a kód v hlavičce a spustí překlady
 */
function updateLangUI() {
    const lang = (window.currentLanguage && ["cs", "en", "fr"].includes(window.currentLanguage))
        ? window.currentLanguage
        : (localStorage.getItem("medstudio_lang") || "cs");

    const flagEl = document.getElementById("headerLangFlag");
    const codeEl = document.getElementById("headerLangCode");
    const flags = { cs: "🇨🇿", en: "🇬🇧", fr: "🇫🇷" };

    if (flagEl) flagEl.textContent = flags[lang] || "🇨🇿";
    if (codeEl) codeEl.textContent = lang.toUpperCase();

    ["cs", "en", "fr"].forEach(l => {
        const check = document.getElementById(`langCheck-${l}`);
        if (check) check.classList.toggle("hidden", l !== lang);
    });

    document.documentElement.lang = lang;

    if (typeof applyTranslations === "function") {
        applyTranslations(lang);
    }
}
window.updateLangUI = updateLangUI;

// Globální posluchač pro zavření dropdownu při kliku mimo
document.addEventListener("click", function(e) {
    const dropdown = document.getElementById("langDropdown");
    const btn = document.getElementById("btnLangSwitcher");
    if (!dropdown || dropdown.classList.contains("hidden")) return;
    if (btn && btn.contains(e.target)) return;
    if (dropdown.contains(e.target)) return;
    dropdown.classList.add("hidden");
});

