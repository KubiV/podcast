/**
 * Vrátí překlad pro zadaný klíč a aktuální jazyk.
 * Podporuje volitelnou interpolaci parametrů ve formátu {paramName}.
 */
function t(key, defaultVal = "", params = null) {
    const lang = (window.currentLanguage && ["cs", "en", "fr"].includes(window.currentLanguage))
        ? window.currentLanguage
        : (localStorage.getItem("medstudio_lang") || "cs");
    const dict = (window.I18N_TRANSLATIONS && window.I18N_TRANSLATIONS[lang]) || (window.I18N_TRANSLATIONS && window.I18N_TRANSLATIONS["cs"]) || {};
    let text = dict[key] !== undefined ? dict[key] : (defaultVal || key);
    if (params && typeof params === "object") {
        for (const [k, v] of Object.entries(params)) {
            text = text.replaceAll(`{${k}}`, v !== undefined && v !== null ? v : "");
        }
    }
    return text;
}
window.t = t;

/**
 * Aplikuje překlady na veškeré elementy v DOMu s patřičnými atributy.
 * Volitelně přijímá kořenový element (root), výchozí je celý document.
 */
function applyTranslations(lang, root = document) {
    if (!lang) {
        lang = (window.currentLanguage && ["cs", "en", "fr"].includes(window.currentLanguage))
            ? window.currentLanguage
            : (localStorage.getItem("medstudio_lang") || "cs");
    }
    if (!["cs", "en", "fr"].includes(lang)) lang = "cs";

    const translations = window.I18N_TRANSLATIONS || {};
    const dict = translations[lang] || translations["cs"] || {};
    const container = root || document;

    // 1. Text elements: data-i18n
    container.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (dict[key] !== undefined) {
            el.textContent = dict[key];
        }
    });

    // 2. HTML elements: data-i18n-html
    container.querySelectorAll("[data-i18n-html]").forEach(el => {
        const key = el.getAttribute("data-i18n-html");
        if (dict[key] !== undefined) {
            el.innerHTML = dict[key];
        }
    });

    // 3. Placeholders: data-i18n-placeholder
    container.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (dict[key] !== undefined) {
            el.placeholder = dict[key];
        }
    });

    // 4. Tooltips/Titles: data-i18n-title
    container.querySelectorAll("[data-i18n-title]").forEach(el => {
        const key = el.getAttribute("data-i18n-title");
        if (dict[key] !== undefined) {
            el.title = dict[key];
        }
    });

    // 5. Form values/buttons: data-i18n-value
    container.querySelectorAll("[data-i18n-value]").forEach(el => {
        const key = el.getAttribute("data-i18n-value");
        if (dict[key] !== undefined) {
            el.value = dict[key];
        }
    });
}
window.applyTranslations = applyTranslations;

/**
 * Globální toast notifikace (plovoucí zpráva v pravém dolním rohu)
 */
function showGlobalToast(message, type = "info") {
    let container = document.getElementById("globalToastContainer");
    if (!container) {
        container = document.createElement("div");
        container.id = "globalToastContainer";
        container.className = "fixed bottom-5 right-5 z-[999999] flex flex-col gap-2 pointer-events-none max-w-sm w-full px-4";
        document.body.appendChild(container);
    }
    const toast = document.createElement("div");
    const colors = {
        success: "bg-emerald-950/90 border-emerald-500/60 text-emerald-100",
        error: "bg-rose-950/90 border-rose-500/60 text-rose-100",
        warning: "bg-amber-950/90 border-amber-500/60 text-amber-100",
        info: "bg-slate-900/95 border-sky-500/60 text-sky-100"
    };
    const colorClass = colors[type] || colors.info;
    toast.className = `${colorClass} border backdrop-blur-md px-4 py-2.5 rounded-xl shadow-2xl text-xs sm:text-sm font-medium transition-all duration-300 transform translate-y-2 opacity-0 pointer-events-auto flex items-center gap-2`;
    toast.textContent = message;
    container.appendChild(toast);
    requestAnimationFrame(() => {
        toast.classList.remove("translate-y-2", "opacity-0");
        toast.classList.add("translate-y-0", "opacity-100");
    });
    setTimeout(() => {
        toast.classList.add("opacity-0", "translate-y-2");
        setTimeout(() => toast.remove(), 350);
    }, 3500);
}
window.showGlobalToast = showGlobalToast;

